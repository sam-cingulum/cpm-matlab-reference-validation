function report=run_robustfit_initial_ols_scale_rounding_v1()
% Numerical floating-point reduction forensics; independent original robustfit
% initial OLS sigma, 24 previously-disclosed synthetic raw-x/y cohorts.
% Legitimate original MathWorks API observations only; NO source extraction.
assert(exist('OCTAVE_VERSION','builtin')==0);
assert(strcmp(version('-release'),'2026b'));
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'robustfit_source_fd_prospective_v1');
m=jsondecode(fileread(fullfile(base,'manifest.json')));
d=jsondecode(fileread(fullfile(base,'input.json')));
assert(m.samples==24 && numel(d.samples)==24);
names={'sqrt_sum_r0_sq_over_df',...
 'norm_r0_over_sqrt_df',...
 'sqrt_sum_r0_sq_over_sqrt_df',...
 'sqrt_dot_r0_over_df',...
 'sqrt_inner_r0_over_df',...
 'norm_r0_times_reciprocal_sqrt_df',...
 'sqrt_sum_r0_sq_times_reciprocal_df',...
 'sqrt_sum_r0_sq_times_reciprocal_sqrt_df',...
 'sqrt_inner_r0_times_reciprocal_sqrt_df',...
 'sqrt_sum_r0sq_over_df_alt',...
 'sqrt_sum_Qp_residual_sq_over_df',...
 'norm_Qp_residual_over_sqrt_df',...
 'sqrt_dot_Qp_residual_over_df',...
 'sqrt_sum_original_Qy_proj_sq_over_df',...
 'norm_original_Qy_proj_over_sqrt_df',...
 'sqrt_sum_X_backslash_y_residual_sq_over_df',...
 'norm_X_backslash_y_residual_over_sqrt_df',...
 'sqrt_sum_Qp_residual_sq_times_reciprocal_df',...
 'std_original_beta_initial_residual_df_adjusted',...
 'sqrt_sum_OLS_y_minus_QQy_sq_over_df',...
 'norm_y_minus_QQy_over_sqrt_df',...
 'sqrt_pythagorean_projection_RSS_over_df',...
 'sqrt_pythagorean_source_Qy_RSS_over_df',...
 'sqrt_sum_original_R_initial_beta_residual_sq_over_df',...
 'sqrt_sum_original_initial_y_minus_X_beta_sq_over_df'};
fields=struct('id',{},'n',{},'source_ols_s_hex',{},...
 'candidate_hex',{},'matches',{},'original_initial_beta_hex',{},...
 'raw_initial_beta_hex',{},'source_Qy_hex',{});
total=zeros(1,numel(names));
for k=1:24
 z=d.samples(k);x=double(z.x(:));y=double(z.y(:));
 n=numel(x);df=n-2;X=[ones(n,1),x];
 [b,st]=robustfit(x,y);
 clone=cpm_independent_bisquare_fit_raw_v1(x,y);
 assert(isequal(num2hex(b),num2hex(clone.beta)));
 bp=clone.initial_beta;
 r0=y-X*bp;
 [Qp,Rp,p]=qr(X,'econ','vector');
 Qy=Qp'*y;
 rp=y-Qp*Qy;
 rq=y-Qp*st.Qy(:);
 ro=y-X*(X\y);
 rnorm=norm(r0);qnorm=norm(rp);
 ols_src=st.ols_s;
 rs2=sum(r0.^2);
 candidates=[sqrt(rs2/df),...
 rnorm/sqrt(df),sqrt(rs2)/sqrt(df),...
 sqrt(dot(r0,r0)/df),sqrt((r0'*r0)/df),...
 rnorm*(1/sqrt(df)),sqrt(rs2*(1/df)),...
 sqrt(rs2)*(1/sqrt(df)),sqrt((r0'*r0))*(1/sqrt(df)),...
 sqrt(sum(r0.*r0)/df),...
 sqrt(sum(rp.^2)/df),qnorm/sqrt(df),sqrt(dot(rp,rp)/df),...
 sqrt(sum(rq.^2)/df),norm(rq)/sqrt(df),...
 sqrt(sum(ro.^2)/df),norm(ro)/sqrt(df),...
 sqrt(sum(rp.^2)*(1/df)),...
 std(r0,0)*sqrt((n-1)/df),...
 sqrt(sum((y-Qp*(Qp'*y)).^2)/df),...
 norm(y-Qp*(Qp'*y))/sqrt(df),...
 sqrt((sum(y.^2)-sum(Qy.^2))/df),...
 sqrt((sum(y.^2)-sum(st.Qy(:).^2))/df),...
 sqrt(sum((y-X*clone.initial_beta).^2)/df),...
 sqrt(sum((y-X*(Rp\(Qp'*y))).^2)/df)];
 assert(numel(candidates)==numel(names));
 rec=struct;rec.id=z.id;rec.n=n;
 rec.source_ols_s_hex=num2hex(ols_src);
 rec.candidate_hex=cellstr(num2hex(candidates(:)))';
 rec.matches=double(strcmp(rec.candidate_hex,rec.source_ols_s_hex));
 rec.original_initial_beta_hex=cellstr(num2hex(bp))';
 rec.raw_initial_beta_hex=cellstr(num2hex(X\y))';
 rec.source_Qy_hex=cellstr(num2hex(st.Qy(:)))';
 total=total+rec.matches;
 fields(end+1)=rec; %#ok<AGROW>
end
report=struct('status','GENUINE_MATHWORKS_R2026B_ORIGINAL_INITIAL_OLS_S_SOURCE_NUMERIC_REDUCTIONS',...
 'runtime','MathWorks MATLAB','release','2026b',...
 'source_original_unmodified',true,...
 'previously_disclosed_input',true,...
 'source_code_never_accessed',true,...
 'source_sha256',m.input_sha256,'count',24,'names',{names},...
 'exact_match_count_by_method',total,...
 'records',fields);
out=fullfile(root,'robustfit_initial_ols_scale_rounding_v1');
if ~exist(out,'dir'),mkdir(out);end
fd=fopen(fullfile(out,'ols_s_original_numeric_reduction.json'),'w');assert(fd>0);
closed=onCleanup(@()fclose(fd));
fprintf(fd,'%s\n',jsonencode(report));
for j=1:numel(names)
 fprintf('%s EXACT %d/24\n',names{j},total(j));
end
end
