function run_original_v241()
% V241 genuine MATLAB R2026b Update 1 source-DISCLOSED original-only
% SIX-column robustfit leverage right-division and QR numerical diagnostics.
% No original private MathWorks source code or local variable names accessed.
% 12 synthetic V211 p=5 predictors + intercept, n=33,49,73.
assert(exist('OCTAVE_VERSION','builtin')==0);
assert(contains(version,'(R2026b) Update 1'));
assert(strcmp(getenv('MKL_CBWR'),'COMPATIBLE'));
maxNumCompThreads(1);assert(maxNumCompThreads==1);
root=fileparts(mfilename('fullpath'));
raw=jsondecode(fileread(fullfile(root,'input.json')));
assert(strcmp(raw.schema,'CINGULUM_V211_R2026B_RAW_MULTIPREDICTOR_ROBUSTFIT_FIRST_BLIND'));
assert(raw.seed==202611220211 && numel(raw.cases)==48);
rows=struct('id',{},'rep',{},'n',{},'p',{},'source_original_b_hex',{},...
 'original_source_R_hex',{},'original_source_h_hex',{},...
 'original_public_pivot_one_based',{},'original_pivot_R_hex',{},...
 'original_economy_Q_hex',{},...
 'right_stats_R_division_Z_hex',{},'transpose_left_R_division_Z_hex',{},...
 'pivoted_R_division_Z_hex',{},...
 'candidate_h',{});
for rep=1:2
 for index=1:48
  c=raw.cases(index);
  if double(c.p)~=5,continue;end
  n=double(c.n);p=double(c.p)+1;
  X=reshape(hex2num(char(c.x_colmajor_hex)),n,5);
  y=hex2num(char(c.y_hex));y=y(:);
  A=[ones(n,1),X];
  [b,s]=robustfit(X,y);
  assert(isequal(size(s.R),[p,p]) && numel(s.h)==n);
  [Q,Rp,pivot]=qr(A,'econ','vector');
  assert(isequal(sort(pivot),1:p));
  Zright=A/s.R;
  Zleft=(s.R'\A')';
  Zpivot=A(:,pivot)/Rp;
  assert(isequal(size(Zright),[n,p]) && isequal(size(Zleft),[n,p]));
  Hsource=s.h;
  Hright=sum(Zright.^2,2);
  Hleft=sum(Zleft.^2,2);
  Hpivot=sum(Zpivot.^2,2);
  Hq=sum(Q.^2,2);
  % Original capped h according to robustfit source-disclosed observations.
  policies=struct( ...
   'public_right_division_h_hex',{bits(min(Hright,0.9999))}, ...
   'transpose_left_solve_h_hex',{bits(min(Hleft,0.9999))}, ...
   'pivoted_R_division_h_hex',{bits(min(Hpivot,0.9999))}, ...
   'Q_column_square_sum_h_hex',{bits(min(Hq,0.9999))}, ...
   'right_division_h_uncapped_hex',{bits(Hright)});
  rows(end+1)=struct('id',c.id,'rep',rep,'n',n,'p',5,...
   'source_original_b_hex',{bits(b)},...
   'original_source_R_hex',{bits(s.R)},...
   'original_source_h_hex',{bits(Hsource)},...
   'original_public_pivot_one_based',pivot,...
   'original_pivot_R_hex',{bits(Rp)},...
   'original_economy_Q_hex',{bits(Q)},...
   'right_stats_R_division_Z_hex',{bits(Zright)},...
   'transpose_left_R_division_Z_hex',{bits(Zleft)},...
   'pivoted_R_division_Z_hex',{bits(Zpivot)},...
   'candidate_h',policies); %#ok<AGROW>
 end
end
assert(numel(rows)==24);
for j=1:12
 a=rmfield(rows(j),'rep');b=rmfield(rows(j+12),'rep');
 assert(isequal(a,b),'V241 original computations must repeat exactly');
end
result=struct('classification','V241_SOURCE_DISCLOSED_ORIGINAL_MATHWORKS_6_COLUMN_LEVERAGE_RIGHT_SOLVER_OBSERVATIONS',...
 'release',version,'mkl_cbwr',getenv('MKL_CBWR'),...
 'run',getenv('GITHUB_RUN_ID'),'source_disclosed',true,...
 'new_original_source_unseen_certification',false,...
 'original_MathWorks_source_code_imported_or_exported',false,...
 'input_sha256','5836d8f460b64c889feda69ee69dc4792a5ff85bf120600f346171150eb2a559',...
 'cohort_count',12,'repetitions',2,'rows',rows);
f=fopen(fullfile(root,'original.json'),'w');assert(f>0);
cleanup=onCleanup(@()fclose(f));
fprintf(f,'%s\n',jsonencode(result));
end
function h=bits(v)
h=cellstr(num2hex(double(v(:))));
end
