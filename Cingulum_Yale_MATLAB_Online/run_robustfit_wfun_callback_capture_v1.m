function report=run_robustfit_wfun_callback_capture_v1()
% Genuine MathWorks R2026b numeric callback observation only. User-authored
% weight function receives authentic runtime vectors during the ORIGINAL
% unmodified robustfit fitting procedure. No MathWorks source code exported.
assert(~exist('OCTAVE_VERSION','builtin') && strcmp(version('-release'),'2026b'));
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'robustfit_source_fd_prospective_v1');
m=jsondecode(fileread(fullfile(base,'manifest.json')));
d=jsondecode(fileread(fullfile(base,'input.json')));
assert(strcmp(m.experiment_id,'mathworks-robustfit-source-fd-prospective-20261111-v1'));
assert(numel(d.samples)==24 && m.samples==24);
global CINGULUM_MATLAB_WFUN_OBSERVATIONS;
records=struct('id',{},'original_source_scale_hex',{},...
 'custom_wfun_robust_s_hex',{},'custom_wfun_matches_source_exact',{},...
 'callback_total_calls',{},'last_calls',{},'postfit_standard_u_hex',{},...
 'postfit_mad_s_hex',{},'postfit_h_hex',{},...
 'original_source_slope_hex',{},'custom_slope_hex',{},...
 'custom_slope_matches_source_exact',{});
for k=1:numel(d.samples)
 item=d.samples(k);x=double(item.x(:));y=double(item.y(:));
 [original_b,st]=robustfit(x,y);
 CINGULUM_MATLAB_WFUN_OBSERVATIONS={};
 [cb,ct]=robustfit(x,y,@observed_bisquare,4.685);
 capture=CINGULUM_MATLAB_WFUN_OBSERVATIONS;
 assert(all(isfinite([cb(:);ct.robust_s;ct.t(2);st.robust_s])));
 calls=cell(1,min(8,numel(capture)));
 for ci=1:numel(calls)
  observed=capture{end-numel(calls)+ci};
  calls{ci}=struct('index_from_end',ci-numel(calls)-1,...
                   'u',double(observed(:)'),...
                   'hex',{cellstr(num2hex(double(observed(:))))'});
 end
 post_u=(st.resid(:)./sqrt(1-st.h(:)))./(st.mad_s*4.685);
 rec=struct('id',item.id,...
   'original_source_scale_hex',num2hex(st.robust_s),...
   'custom_wfun_robust_s_hex',num2hex(ct.robust_s),...
   'custom_wfun_matches_source_exact',...
      strcmp(num2hex(st.robust_s),num2hex(ct.robust_s)),...
   'callback_total_calls',numel(capture),...
   'last_calls',{calls},...
   'postfit_standard_u_hex',{cellstr(num2hex(post_u))'},...
   'postfit_mad_s_hex',num2hex(st.mad_s),...
   'postfit_h_hex',{cellstr(num2hex(st.h(:)))'},...
   'original_source_slope_hex',num2hex(original_b(2)),...
   'custom_slope_hex',num2hex(cb(2)),...
   'custom_slope_matches_source_exact',...
      strcmp(num2hex(original_b(2)),num2hex(cb(2))));
 records(end+1)=rec; %#ok<AGROW>
 CINGULUM_MATLAB_WFUN_OBSERVATIONS={};
end
assert(numel(records)==24);
report=struct('status','ORIGINAL_UNMODIFIED_MATHWORKS_CALLBACK_VECTOR_NUMERICAL_OBSERVATIONS',...
 'runtime','MathWorks MATLAB','release','2026b',...
 'original_robustfit_source_unmodified',true,...
 'custom_callback_is_independently_authored',true,...
 'numeric_observations_only_no_proprietary_source',true,...
 'all_cases_previously_disclosed',true,...
 'original_source_input_sha256',m.input_sha256,...
 'source_commit',m.source_commit,...
 'sample_count',24,'records',records);
outdir=fullfile(root,'robustfit_wfun_callback_capture_v1');
if ~exist(outdir,'dir'),mkdir(outdir);end
fid=fopen(fullfile(outdir,'callback_numeric_observations.json'),'w');assert(fid>0);
cleanuper=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report));
fprintf('AUTHENTIC_MATHWORKS_BISQUARE_CALLBACK_SAMPLES=%d CUSTOM_SOURCE_SCALE_MATCHES=%d\n',...
 numel(records),sum([records.custom_wfun_matches_source_exact]));
end

function w=observed_bisquare(u)
% Our own bisquare weight code; stores *only numeric callback inputs*.
global CINGULUM_MATLAB_WFUN_OBSERVATIONS;
CINGULUM_MATLAB_WFUN_OBSERVATIONS{end+1}=double(u(:));
w=double(abs(u)<1).*(1-u.^2).^2;
end
