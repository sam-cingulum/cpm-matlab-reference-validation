function report=run_robustfit_stage_numerics_v2()
% R2026b numerical black-box for already disclosed frozen 24 source cases.
% Observable original robustfit inputs/outputs only; original implementation
% is unchanged, and no MathWorks proprietary function source is exported.
assert(~exist('OCTAVE_VERSION','builtin') && strcmp(version('-release'),'2026b'));
root=fileparts(mfilename('fullpath'));
dirin=fullfile(root,'robustfit_source_fd_prospective_v1');
m=jsondecode(fileread(fullfile(dirin,'manifest.json')));
assert(strcmp(m.experiment_id,'mathworks-robustfit-source-fd-prospective-20261111-v1'));
d=jsondecode(fileread(fullfile(dirin,'input.json')));
assert(numel(d.samples)==24);
template=struct('id','','source_robust_s_hex','','source_scale',0,...
 'reconstructed_formula_match_count',0,...
 'formula_bits',{{}},'formula_numeric',[],...
 'r',[],'h',[],'mad_s',0,'ols_s',0,'tune',4.685,...
 'u',[],'phi',[],'dphi',[],'m1_hex','','m2_hex','','K_hex','',...
 'm1',0,'m2',0,'K',0,'r22_hex','','s_hex','','slope_hex','');
res=repmat(template,1,24);
for i=1:24
 item=d.samples(i);x=double(item.x(:));y=double(item.y(:));
 [b,st]=robustfit(x,y);
 n=numel(x);p=2;delta=.0001;
 r=st.resid(:)./sqrt(1-st.h(:));
 u=r./(st.mad_s*4.685);
 phi=u.*((abs(u)<1).*(1-u.^2).^2);
 u1=u-delta;phi0=u1.*((abs(u1)<1).*(1-u1.^2).^2);
 u1=u+delta;phi1=u1.*((abs(u1)<1).*(1-u1.^2).^2);
 dphi=(phi1-phi0)./(2*delta);
 m1=mean(dphi);m2=sum((1-st.h(:)).*(phi.^2))/(n-p);
 K=1+(p/n)*(1-m1)/m1;
 stune=st.mad_s*4.685;
 candidates=[...
   K*sqrt(m2)*stune/m1,...
   stune*K*sqrt(m2)/m1,...
   K*stune*sqrt(m2)/m1,...
   stune*sqrt(m2)*K/m1,...
   (K*sqrt(m2))*(stune/m1),...
   stune*(K*sqrt(m2))/m1,...
   (K/m1)*sqrt(m2)*stune,...
   (sqrt(m2)/m1)*stune*K,...
   (stune*sqrt(m2))*(K/m1),...
   K*(sqrt(m2)*stune/m1),...
   (K*stune/m1)*sqrt(m2),...
   (stune/m1)*sqrt(m2)*K];
 hexes=cell(1,numel(candidates));
 for j=1:numel(candidates),hexes{j}=num2hex(candidates(j));end
 sourcehex=num2hex(st.robust_s);
 matches=sum(strcmp(hexes,sourcehex));
 rec=template;
 rec.id=item.id;rec.source_robust_s_hex=sourcehex;
 rec.source_scale=st.robust_s;rec.reconstructed_formula_match_count=matches;
 rec.formula_bits=hexes;rec.formula_numeric=candidates;
 rec.r=r(:)';rec.h=st.h(:)';rec.mad_s=st.mad_s;
 rec.ols_s=st.ols_s;rec.u=u(:)';rec.phi=phi(:)';rec.dphi=dphi(:)';
 rec.m1=m1;rec.m2=m2;rec.K=K;
 rec.m1_hex=num2hex(m1);rec.m2_hex=num2hex(m2);
 rec.K_hex=num2hex(K);rec.r22_hex=num2hex(st.R(2,2));
 rec.s_hex=num2hex(st.s);rec.slope_hex=num2hex(b(2));
 res(i)=rec;
end
report=struct('status','POSTHOC_GENUINE_MATLAB_COMPONENT_INTERNAL_NUMERICS',...
 'runtime','MathWorks MATLAB','release','2026b',...
 'real_original_source_unmodified',true,...
 'prospective_cases_already_disclosed',true,...
 'old_frozen_forecasts_untouched',true,...
 'source_commit',m.source_commit,'original_input_sha256',m.input_sha256,...
 'sample_count',24,'records',res);
outdir=fullfile(root,'robustfit_source_fd_stage_v2');
if ~exist(outdir,'dir'),mkdir(outdir);end
fid=fopen(fullfile(outdir,'source_stage_numerics.json'),'w');assert(fid>0);
closefile=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report));
fprintf('ORIGINAL_SOURCE_STAGE_MATHEMATICAL_RECONSTRUCTIONS=%d\n',sum([res.reconstructed_formula_match_count]>0));
end
