function report=run_qr_householder_full_bit_capture_v1()
% Genuine R2026b public-API full binary64 capture on ALREADY disclosed
% synthetic cohorts. Does NOT expose private internal LAPACK temporaries.
assert(exist('OCTAVE_VERSION','builtin')==0);
assert(strcmp(version('-release'),'2026b'));
maxNumCompThreads(1);
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'robustfit_raw_full_source_unseen_v1');
raw=jsondecode(fileread(fullfile(base,'input.json')));
assert(numel(raw.cases)==48);
records=cell(48,1);
for k=1:48
 c=raw.cases(k);x=double(c.x(:));y=double(c.y(:));n=numel(x);
 X=[ones(n,1),x];
 [~,st]=robustfit(x,y);
 [Q,Rp,p]=qr(X,'econ','vector');
 [Q0,R0]=qr(X,0);
 p=double(p(:)');
 assert(isequal(sort(p),1:2));
 first=X(:,p(1));second=X(:,p(2));
 beta=Rp(1,1);alpha=first(1);
 v=[1; first(2:end)./(alpha-beta)];
 tau=(beta-alpha)/beta;
 terms=v.*second;
 sequential=zeros(n,1);running=0;
 for i=1:n
  running=running+terms(i);sequential(i)=running;
 end
 cumsum_builtin=cumsum(terms);
 dot_builtin=dot(v,second);
 matrix_product=v'*second;
 sum_builtin=sum(terms);
 transformed_matrix=second-tau*v*(v'*second);
 transformed_dot=second-tau*v*dot_builtin;
 transformed_sum=second-tau*v*sum_builtin;
 transformed_sequential=second-tau*v*running;
 transformed_left=second-(tau*(v'*second))*v;
 transformed_fused=second-tau*(v*(v'*second));
 Rorig=Rp;
 if isequal(p,[2 1]),Rorig=Rp([2 1],[2 1]);end
 row=struct('id',c.id,'n',n,'pivot',p,...
  'raw_x_hex',{cellstr(num2hex(x))'},'raw_y_hex',{cellstr(num2hex(y))'},...
  'X_hex',{cellstr(num2hex(X(:)))'},...
  'original_robustfit_R_hex',{cellstr(num2hex(st.R(:)))'},...
  'original_robustfit_h_hex',{cellstr(num2hex(st.h(:)))'},...
  'public_pivot_R_hex',{cellstr(num2hex(Rp(:)))'},...
  'public_pivot_Q_hex',{cellstr(num2hex(Q(:)))'},...
  'public_nonpivot_R_hex',{cellstr(num2hex(R0(:)))'},...
  'public_nonpivot_Q_hex',{cellstr(num2hex(Q0(:)))'},...
  'first_raw_hex',{cellstr(num2hex(first))'},...
  'second_raw_hex',{cellstr(num2hex(second))'},...
  'first_alpha_hex',num2hex(alpha),'first_beta_hex',num2hex(beta),...
  'first_tau_reconstructed_hex',num2hex(tau),...
  'first_v_reconstructed_hex',{cellstr(num2hex(v))'},...
  'first_dot_terms_hex',{cellstr(num2hex(terms))'},...
  'first_dot_prefix_sequential_hex',{cellstr(num2hex(sequential))'},...
  'first_dot_prefix_cumsum_hex',{cellstr(num2hex(cumsum_builtin))'},...
  'first_dot_builtin_hex',num2hex(dot_builtin),...
  'first_dot_matmul_hex',num2hex(matrix_product),...
  'first_dot_sum_hex',num2hex(sum_builtin),...
  'first_dot_sequential_hex',num2hex(running),...
  'transformed_matrix_hex',{cellstr(num2hex(transformed_matrix))'},...
  'transformed_dot_hex',{cellstr(num2hex(transformed_dot))'},...
  'transformed_sum_hex',{cellstr(num2hex(transformed_sum))'},...
  'transformed_sequential_hex',{cellstr(num2hex(transformed_sequential))'},...
  'transformed_left_hex',{cellstr(num2hex(transformed_left))'},...
  'transformed_fused_hex',{cellstr(num2hex(transformed_fused))'},...
  'source_equals_public_pivot_R',isequal(num2hex(st.R(:)),num2hex(Rorig(:))));
 records{k}=row;
end
[~,cpu]=system('grep -m 1 "model name" /proc/cpuinfo');
[~,os]=system('uname -a');
report=struct('status','GENUINE_MATHWORKS_R2026B_PUBLIC_QR_FULL_BIT_CAPTURE_V1',...
 'not_prospective',true,'source_original_unmodified',true,...
 'private_qr_intermediates_not_observable',true,...
 'first_reflector_v_tau_reconstructed_not_internal',true,...
 'release',version('-release'),'matlab_version',version,...
 'cpu',strtrim(cpu),'uname',strtrim(os),'computer',computer,...
 'max_threads',maxNumCompThreads,'mkl_cbwr',getenv('MKL_CBWR'),...
 'mkl_num_threads',getenv('MKL_NUM_THREADS'),...
 'omp_num_threads',getenv('OMP_NUM_THREADS'),...
 'github_sha',getenv('GITHUB_SHA'),'github_run_id',getenv('GITHUB_RUN_ID'),...
 'case_count',48,'records',{records});
out=fullfile(root,'native_qr_retro_same_runner_v1','full_bit_capture_v1.json');
assert(~exist(out,'file'));
fid=fopen(out,'w');assert(fid>0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report));
assert(all(cellfun(@(z)z.source_equals_public_pivot_R,records)));
fprintf('GENUINE_MATLAB_PUBLIC_QR_FULL_BIT_CAPTURE_48_CASES_COMPLETE\n');
end
