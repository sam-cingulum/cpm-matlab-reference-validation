function report=run_robustfit_raw_y_residual_mad_ols_forensics_v1()
% Genuine MathWorks R2026b numeric API, already disclosed source inputs.
% Independently identify exact original robustfit residual, leverage-adjusted
% MAD, initial OLS scale from raw predictor and outcomes. NO source extracted.
assert(exist('OCTAVE_VERSION','builtin')==0);
assert(strcmp(version('-release'),'2026b'));
root=fileparts(mfilename('fullpath'));
folder=fullfile(root,'robustfit_source_fd_prospective_v1');
m=jsondecode(fileread(fullfile(folder,'manifest.json')));
data=jsondecode(fileread(fullfile(folder,'input.json')));
assert(m.samples==24 && numel(data.samples)==24 && m.source_not_run);
resnames={'matrix_y_minus_Xtimes_beta',...
 'vector_y_minus_intercept_plus_slope_x',...
 'vector_y_minus_slope_x_plus_intercept',...
 'left_associative_y_minus_intercept_then_slope_x',...
 'vector_y_minus_x_slope_then_intercept'};
madnames={'corrected_resid_reciprocal_first_sorted_skip_one',...
 'corrected_resid_direct_division_sorted_skip_one',...
 'corrected_resid_reciprocal_first_full_median',...
 'corrected_resid_skip_one_multiply_reciprocal_c',...
 'corrected_resid_direct_division_full_median',...
 'corrected_resid_reciprocal_first_sorted_skip_two'};
olsnames={'sumsq_over_df_then_sqrt',...
 'norm_over_sqrt_df',...
 'sqrt_sumsq_over_sqrt_df',...
 'matrix_OLS_QR_transform_residual_sumsq_df',...
 'ordinary_sum_squared_norm_then_df'};
tpl=struct('id','','n',0,...
 'source_ols_s_hex','','source_mad_s_hex','',...
 'residual_exact_counts',zeros(1,5),...
 'mad_exact_counts',zeros(1,6),...
 'ols_exact_counts',zeros(1,5),...
 'source_residual_hex',{{}},...
 'residual_candidates_hex',{{}},...
 'mad_candidates_hex',{{}},...
 'ols_candidates_hex',{{}},...
 'original_robustfit_unmodified',true);
rows=repmat(tpl,1,24);
for k=1:24
 q=data.samples(k);x=double(q.x(:));y=double(q.y(:));
 n=numel(x);X=[ones(n,1),x];
 [b,st]=robustfit(x,y);
 [Q,R,p]=qr(X,'econ','vector');
 Rp=R;if isequal(double(p(:)'),[2,1]),Rp=R([2 1],[2 1]);end
 % QR and hat leverage source reconstruction: already-disclosed 24/24 and
 % 1032/1032 in previous independent genuine numeric experiments.
 assert(isequal(num2hex(Rp),num2hex(st.R)));
 Z=X/Rp;h=sum(Z.^2,2);
 assert(isequal(num2hex(h),num2hex(st.h(:))));
 residuals=[y-X*b,...
   y-(b(1)+b(2)*x),...
   y-(x*b(2)+b(1)),...
   (y-b(1))-b(2)*x,...
   (y-b(2)*x)-b(1)];
 source_res=st.resid(:);
 sorted_direct=sort(abs(source_res./sqrt(1-h)));
 sorted_recip=sort(abs(source_res.*(1./sqrt(1-h))));
 mad_candidates=[median(sorted_recip(2:end))/0.6745,...
  median(sorted_direct(2:end))/0.6745,...
  median(sorted_recip)/0.6745,...
  median(sorted_recip(2:end))*(1/0.6745),...
  median(sorted_direct)/0.6745,...
  median(sorted_recip(3:end))/0.6745];
 % Backslash and published OLS formula, not original source implementation.
 olsbeta=X\y;
 OLSres=y-X*olsbeta;
 [Qp,Rp0,p0]=qr(X,'econ','vector');
 olsres_from_q=y-Qp*(Qp'*y);
 ols_candidates=[sqrt(sum(OLSres.^2)/(n-2)),...
  norm(OLSres)/sqrt(n-2),...
  sqrt(sum(OLSres.^2))/sqrt(n-2),...
  sqrt(sum(olsres_from_q.^2)/(n-2)),...
  sqrt(norm(OLSres)^2/(n-2))];
 row=tpl;row.id=q.id;row.n=n;
 row.source_ols_s_hex=num2hex(st.ols_s);
 row.source_mad_s_hex=num2hex(st.mad_s);
 row.source_residual_hex=cellstr(num2hex(source_res))';
 row.residual_candidates_hex=cell(1,numel(resnames));
 row.mad_candidates_hex=cell(1,numel(madnames));
 row.ols_candidates_hex=cell(1,numel(olsnames));
 for j=1:numel(resnames)
   hhex=cellstr(num2hex(residuals(:,j)));
   row.residual_exact_counts(j)=sum(strcmp(hhex,row.source_residual_hex(:)));
   row.residual_candidates_hex{j}=hhex';
 end
 for j=1:numel(madnames)
  row.mad_candidates_hex{j}=num2hex(mad_candidates(j));
  row.mad_exact_counts(j)=strcmp(row.mad_candidates_hex{j},row.source_mad_s_hex);
 end
 for j=1:numel(olsnames)
  row.ols_candidates_hex{j}=num2hex(ols_candidates(j));
  row.ols_exact_counts(j)=strcmp(row.ols_candidates_hex{j},row.source_ols_s_hex);
 end
 rows(k)=row;
end
record_count=numel(rows);
res_tot=zeros(1,numel(resnames));
mad_tot=zeros(1,numel(madnames));
ols_tot=zeros(1,numel(olsnames));
for j=1:numel(resnames),res_tot(j)=sum(arrayfun(@(a)a.residual_exact_counts(j),rows));end
for j=1:numel(madnames),mad_tot(j)=sum(arrayfun(@(a)a.mad_exact_counts(j),rows));end
for j=1:numel(olsnames),ols_tot(j)=sum(arrayfun(@(a)a.ols_exact_counts(j),rows));end
report=struct('status','GENUINE_R2026B_ORIGINAL_RAW_X_Y_RESIDUAL_MAD_OLS_FORENSICS',...
 'runtime','MathWorks MATLAB','release','2026b',...
 'original_source_unmodified',true,...
 'original_inputs_already_disclosed',true,...
 'source_implementation_not_extracted',true,...
 'input_sha256',m.input_sha256,'sample_count',record_count,...
 'residual_element_count',sum([rows.n]),...
 'residual_methods',{resnames},...
 'residual_exact_totals',res_tot,...
 'mad_methods',{madnames},'mad_exact_totals',mad_tot,...
 'ols_methods',{olsnames},'ols_exact_totals',ols_tot,...
 'records',rows);
output=fullfile(root,'robustfit_raw_y_residual_mad_ols_forensics_v1');
if ~exist(output,'dir'),mkdir(output);end
fid=fopen(fullfile(output,'genuine_source_residual_mad_ols.json'),'w');assert(fid>0);
finish=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report));
fprintf('GENUINE_R2026B_ORIGINAL_RESIDUAL_N=%d\n',report.residual_element_count);
for j=1:numel(resnames),fprintf('RESID %s %d\n',resnames{j},res_tot(j));end
for j=1:numel(madnames),fprintf('MAD %s %d\n',madnames{j},mad_tot(j));end
for j=1:numel(olsnames),fprintf('OLS %s %d\n',olsnames{j},ols_tot(j));end
end
