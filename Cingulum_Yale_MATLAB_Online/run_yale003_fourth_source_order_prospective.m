function report = run_yale003_fourth_source_order_prospective()
% Preregistered original-source test, genuine MathWorks MATLAB R2026b.
% Run only against independently frozen source-invisible synthetic inputs.
% Original pinned Yale computeLambdaMax.m is unchanged.
if exist('OCTAVE_VERSION','builtin')~=0
    error('GENUINE_MATHWORKS_REQUIRED');
end
assert(strcmp(version('-release'),'2026b'));
root=fileparts(mfilename('fullpath'));
fixtureDir=fullfile(root,'yale003_fourth_prospective');
manifest=jsondecode(fileread(fullfile(fixtureDir,'manifest.json')));
assert(strcmp(manifest.experiment_id,'yale003-source-order-fourth-20261111-v1'));
assert(strcmp(manifest.source_revision,'b903f83b476b745417b1f062f6777f5ffe118f1a'));
assert(strcmp(manifest.matlab_release,'R2026b'));
assert(strcmp(manifest.original_source_strict_absolute_tolerance,'1e-10'));
assert(manifest.separate_full_output_bitwise_gate);
assert(manifest.fixtures_unseen_before_matlab && ~manifest.patient_data);
assert(strcmp(manifest.source_operand_order_commit,'bda96ff'));
names=fieldnames(manifest.cases);
assert(numel(names)==48);
addpath(fullfile(root,'upstream','yale-cpm','matlab','misc'));
assert(~isempty(which('computeLambdaMax')));
resultDir=fullfile(root,'yale003_fourth_results');
if ~exist(resultDir,'dir'),mkdir(resultDir);end
output=struct('case_name',{},'strict',{},'bitwise',{},'reconstruction_exact',{},...
    'within_contract',{},'abs_lambda_error',{},'abs_null_mse_error',{});
strictCount=0;bitsCount=0;exactReconCount=0;
digestKey=matlab.lang.makeValidName('input.json');
for i=1:numel(names)
    name=names{i};
    spec=manifest.cases.(name);
    assert(isfield(spec.sha256,digestKey));
    folder=fullfile(fixtureDir,name);
    inp=jsondecode(fileread(fullfile(folder,'input.json')));
    rust=jsondecode(fileread(fullfile(folder,'rust.json')));
    X=double(inp.x);Y=double(inp.y(:));w=double(inp.weights(:));
    a=double(inp.alpha);standardize=logical(inp.standardize);
    [n,d]=size(X);
    assert(n==spec.n && d==spec.p && n==numel(Y) && n==numel(w));
    assert(all(isfinite(X),'all')&&all(isfinite(Y))&&all(isfinite(w)));
    assert(all(w>=0)&&any(w>0)&&a>0&&a<=1);
    withinContract=abs(sum(w)-1)<=1e-12;
    assert(withinContract==logical(spec.in_weight_contract));
    % Call the ORIGINAL pinned Yale source without modifying any line.
    [sourceLambda,sourceMse]=computeLambdaMax(X,Y,w,a,standardize);
    % Independently reconstruct exactly the source expressions using
    % MathWorks' own kernels. These values are DIAGNOSTICS, not a modified
    % original function or a claim to identify its private BLAS internals.
    nw=w.'/sum(w);
    muX=nw*X;
    X0=bsxfun(@minus,X,muX);
    if standardize
        sigmaX=sqrt(nw*(X0.^2));
        sigmaX(range(X)==0)=1;
        X0=bsxfun(@rdivide,X0,sigmaX);
    else
        sigmaX=ones(1,d);
    end
    wX0=bsxfun(@times,X0,w);
    muY=w.'*Y;
    Y0=Y-muY;
    featureDots=abs(sum(bsxfun(@times,wX0,Y0)));
    reconstructedLambda=max(featureDots)/a;
    reconstructedMse=w.'*(Y0.^2);
    recon=strcmp(num2hex(sourceLambda),num2hex(reconstructedLambda))&&...
        strcmp(num2hex(sourceMse),num2hex(reconstructedMse));
    exactReconCount=exactReconCount+double(recon);
    ldelta=abs(sourceLambda-double(rust.lambda_max));
    mdelta=abs(sourceMse-double(rust.null_mse));
    strict=ldelta<=1e-10 && mdelta<=1e-10 &&...
        isfinite(sourceLambda)&&isfinite(sourceMse);
    bitwise=strcmp(num2hex(sourceLambda),num2hex(double(rust.lambda_max)))&&...
        strcmp(num2hex(sourceMse),num2hex(double(rust.null_mse)));
    strictCount=strictCount+double(strict);
    bitsCount=bitsCount+double(bitwise);
    observation=struct('runtime','MathWorks MATLAB',...
        'release',version('-release'),...
        'arch',computer('arch'),...
        'threads',maxNumCompThreads,...
        'source_revision',manifest.source_revision,...
        'case_name',name,'n',n,'p',d,...
        'fixture_sha256',spec.sha256.(digestKey),...
        'weight_contract',withinContract,...
        'source_lambda',sourceLambda,'source_mse',sourceMse,...
        'source_lambda_hex',num2hex(sourceLambda),...
        'source_mse_hex',num2hex(sourceMse),...
        'source_reconstruction_exact',recon,...
        'reconstructed_lambda_hex',num2hex(reconstructedLambda),...
        'reconstructed_mse_hex',num2hex(reconstructedMse),...
        'mu_x_hex',{cellstr(num2hex(muX(:)))},...
        'sigma_x_hex',{cellstr(num2hex(sigmaX(:)))},...
        'feature_dot_hex',{cellstr(num2hex(featureDots(:)))},...
        'mu_y_hex',num2hex(muY),...
        'weighted_y_dot_hex',num2hex(dot(w,Y)),...
        'weighted_y_elementwise_hex',num2hex(sum(w.*Y)),...
        'weighted_mse_direct_hex',num2hex(w.'*(Y0.^2)),...
        'weighted_mse_elementwise_hex',num2hex(sum(w.*(Y0.^2))),...
        'strict_pass',strict,'bitwise_pass',bitwise,...
        'original_source_unchanged',true,...
        'patient_data',false);
    save_original(fullfile(resultDir,[name '.json']),observation);
    output(end+1)=struct('case_name',name,'strict',strict,... %#ok<AGROW>
        'bitwise',bitwise,'reconstruction_exact',recon,...
        'within_contract',withinContract,...
        'abs_lambda_error',ldelta,'abs_null_mse_error',mdelta);
    fprintf('YALE003_FOURTH %s strict=%d binary64=%d reconstruct=%d\n',...
        name,strict,bitwise,recon);
end
report=struct('runtime','MathWorks MATLAB',...
    'release',version('-release'),...
    'experiment_id',manifest.experiment_id,...
    'source_revision',manifest.source_revision,...
    'case_count',numel(names),...
    'strict_passes',strictCount,'exact_binary64_both',bitsCount,...
    'source_reconstruction_exact_count',exactReconCount,...
    'gate_strict_all_pass',strictCount==48,...
    'gate_bitwise_all_pass',bitsCount==48,...
    'cases',output);
save_original(fullfile(resultDir,'summary.json'),report);
if exactReconCount~=48
    error('YALE003_FOURTH_ORIGINAL_SOURCE_RECONSTRUCTION_FAILED_OUTPUT_PRESERVED');
end
if strictCount~=48
    error('YALE003_FOURTH_PREREGISTERED_STRICT_GATE_FAILED_OUTPUT_PRESERVED');
end
end

function save_original(path,obj)
fid=fopen(path,'w');assert(fid>0);
closer=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(obj));
end
